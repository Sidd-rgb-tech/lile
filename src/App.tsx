import React, { useState, useEffect } from 'react';
import { AndroidPhoneFrame } from './components/AndroidPhoneFrame';
import { AndroidTopBar } from './components/AndroidTopBar';
import { AndroidBottomNav, MainTab } from './components/AndroidBottomNav';
import { HomeScreen } from './components/screens/HomeScreen';
import { AssistantScreen } from './components/screens/AssistantScreen';
import { ChallengesScreen } from './components/screens/ChallengesScreen';
import { ImpactScreen } from './components/screens/ImpactScreen';
import { PosterGeneratorScreen } from './components/screens/PosterGeneratorScreen';
import { CampaignsScreen } from './components/screens/CampaignsScreen';
import { StoriesScreen } from './components/screens/StoriesScreen';
import { ProfileSettingsScreen } from './components/screens/ProfileSettingsScreen';
import { AndroidStudioCodeModal } from './components/AndroidStudioCodeModal';

import { StorageService } from './services/storage';
import { OnboardingScreen } from './components/screens/OnboardingScreen';
import confetti from 'canvas-confetti';
import {
  UserProfile,
  Challenge,
  ImpactRecord,
  Badge,
  Campaign,
  ImpactStory,
  AwarenessCategory,
  ProofTier
} from './types';

export default function App() {
  // Navigation State
  const [currentTab, setCurrentTab] = useState<MainTab>('home');
  const [currentSubScreen, setCurrentSubScreen] = useState<'campaigns' | 'stories' | 'profile' | null>(null);
  const [selectedCategoryFilter, setSelectedCategoryFilter] = useState<AwarenessCategory | null>(null);
  const [isCodeModalOpen, setIsCodeModalOpen] = useState(false);

  // App Data State (Synced with offline StorageService / Room)
  const [userProfile, setUserProfile] = useState<UserProfile>(() => StorageService.getProfile());
  const [challenges, setChallenges] = useState<Challenge[]>(() => StorageService.getChallenges());
  const [impactRecords, setImpactRecords] = useState<ImpactRecord[]>(() => StorageService.getImpactRecords());
  const [badges, setBadges] = useState<Badge[]>(() => StorageService.getBadges());
  const [campaigns, setCampaigns] = useState<Campaign[]>(() => StorageService.getCampaigns());
  const [stories, setStories] = useState<ImpactStory[]>(() => StorageService.getStories());

  // Reload state from storage
  const reloadData = () => {
    setUserProfile(StorageService.getProfile());
    setChallenges(StorageService.getChallenges());
    setImpactRecords(StorageService.getImpactRecords());
    setBadges(StorageService.getBadges());
    setCampaigns(StorageService.getCampaigns());
    setStories(StorageService.getStories());
  };

  // Challenge Actions
  const handleStartChallenge = (id: string) => {
    const updated = challenges.map(c => {
      if (c.id === id && c.status === 'NOT_STARTED') {
        return { ...c, status: 'IN_PROGRESS' as const };
      }
      return c;
    });
    setChallenges(updated);
    StorageService.saveChallenges(updated);
  };

  const handleCompleteChallenge = (id: string, reflection: string, proofTier: ProofTier) => {
    StorageService.completeChallenge(id, reflection, proofTier);
    reloadData();
  };

  const handleAddCustomChallenge = (challengeData: Partial<Challenge>) => {
    const newChallenge: Challenge = {
      id: `custom-${Date.now()}`,
      title: challengeData.title || 'Custom Awareness Action',
      category: challengeData.category || 'Education & Literacy',
      difficulty: challengeData.difficulty || 'MEDIUM',
      estimatedDurationMinutes: challengeData.estimatedDurationMinutes || 20,
      shortDescription: challengeData.shortDescription || 'Action plan generated by AI Assistant.',
      learningObjective: challengeData.learningObjective || 'Turn awareness into measurable practice.',
      instructions: challengeData.instructions || 'Follow your planned steps and document the outcome.',
      expectedOutcome: challengeData.expectedOutcome || 'Completed planned positive activity.',
      points: challengeData.points || 40,
      status: 'NOT_STARTED',
      proofTier: challengeData.proofTier || 'SELF_REPORTED_ACTION',
      isPointsAwarded: false
    };

    const updated = [newChallenge, ...challenges];
    setChallenges(updated);
    StorageService.saveChallenges(updated);
  };

  // Quick action from Home
  const handleQuickCompleteAction = (actionTitle: string, points: number) => {
    const newRecord: ImpactRecord = {
      id: `rec-${Date.now()}`,
      title: actionTitle,
      category: 'Waste Management & Recycling',
      proofTier: 'SELF_REPORTED_ACTION',
      pointsEarned: points,
      timestamp: Date.now(),
      notes: 'Completed daily recommended action from Home dashboard.'
    };
    const updatedRecords = [newRecord, ...impactRecords];
    setImpactRecords(updatedRecords);
    StorageService.saveImpactRecords(updatedRecords);

    const updatedProfile = {
      ...userProfile,
      totalPoints: userProfile.totalPoints + points,
      currentStreakDays: userProfile.currentStreakDays + 1,
      lastActiveDate: Date.now()
    };
    setUserProfile(updatedProfile);
    StorageService.saveProfile(updatedProfile);
  };

  // Poster points reward
  const handleAwardPosterPoints = () => {
    const posterBadge = badges.find(b => b.id === 'awareness_creator');
    if (posterBadge && !posterBadge.isUnlocked) {
      const updatedBadges = badges.map(b =>
        b.id === 'awareness_creator' ? { ...b, isUnlocked: true, unlockedDate: Date.now(), progress: 1.0 } : b
      );
      setBadges(updatedBadges);
      StorageService.saveBadges(updatedBadges);

      const newRecord: ImpactRecord = {
        id: `rec-${Date.now()}`,
        title: 'Exported Social Awareness Impact Poster',
        category: 'School & Community Improvement',
        proofTier: 'MEASURED_OUTCOME',
        pointsEarned: 35,
        timestamp: Date.now(),
        notes: 'Rendered and saved high-resolution impact poster for community distribution.'
      };
      const updatedRecords = [newRecord, ...impactRecords];
      setImpactRecords(updatedRecords);
      StorageService.saveImpactRecords(updatedRecords);

      const updatedProfile = {
        ...userProfile,
        totalPoints: userProfile.totalPoints + 35
      };
      setUserProfile(updatedProfile);
      StorageService.saveProfile(updatedProfile);
    }
  };

  // Campaign & Story toggles
  const handleToggleJoinCampaign = (campaignId: string) => {
    const updated = campaigns.map(c => {
      if (c.id === campaignId) {
        const isJoined = !c.isJoined;
        return {
          ...c,
          isJoined,
          participantCount: isJoined ? c.participantCount + 1 : c.participantCount - 1
        };
      }
      return c;
    });
    setCampaigns(updated);
    StorageService.saveCampaigns(updated);
  };

  const handleToggleBookmarkStory = (storyId: string) => {
    const updated = stories.map(s => (s.id === storyId ? { ...s, isFavorited: !s.isFavorited } : s));
    setStories(updated);
    StorageService.saveStories(updated);
  };

  const handleResetData = () => {
    StorageService.resetAllDemoData();
    reloadData();
  };

  const handleCompleteOnboarding = (updatedProfile: UserProfile) => {
    setUserProfile(updatedProfile);
    StorageService.saveProfile(updatedProfile);
    confetti({
      particleCount: 75,
      spread: 70,
      origin: { y: 0.6 }
    });
  };

  const handleReplayOnboarding = () => {
    const updated = { ...userProfile, isOnboardingCompleted: false };
    setUserProfile(updated);
    StorageService.saveProfile(updated);
    setCurrentSubScreen(null);
  };

  // Compute top bar title
  const getScreenTitle = () => {
    if (currentSubScreen === 'campaigns') return 'Campaigns';
    if (currentSubScreen === 'stories') return 'Impact Stories';
    if (currentSubScreen === 'profile') return 'Profile & Settings';

    switch (currentTab) {
      case 'home':
        return 'CHANGE360';
      case 'assistant':
        return 'AI Assistant';
      case 'challenges':
        return 'Challenges';
      case 'impact':
        return 'My Impact';
      case 'poster':
        return 'Poster Generator';
      default:
        return 'CHANGE360';
    }
  };

  return (
    <>
      <AndroidPhoneFrame
        onOpenCodeInspector={() => setIsCodeModalOpen(true)}
        onDownloadProjectZip={() => setIsCodeModalOpen(true)}
      >
        {!userProfile.isOnboardingCompleted ? (
          <OnboardingScreen
            currentProfile={userProfile}
            onCompleteOnboarding={handleCompleteOnboarding}
          />
        ) : (
          <>
            {/* Android Material 3 Top App Bar */}
            <AndroidTopBar
              title={getScreenTitle()}
              showBack={currentSubScreen !== null}
              onBack={() => setCurrentSubScreen(null)}
              userProfile={userProfile}
              onOpenProfile={() => setCurrentSubScreen('profile')}
            />

            {/* Dynamic Screen Container */}
            <div className="flex-1 overflow-hidden relative flex flex-col">
              {currentSubScreen === 'campaigns' ? (
                <CampaignsScreen
                  campaigns={campaigns}
                  onToggleJoinCampaign={handleToggleJoinCampaign}
                  onNavigateToPosterForCampaign={camp => {
                    setSelectedCategoryFilter(camp.category);
                    setCurrentSubScreen(null);
                    setCurrentTab('poster');
                  }}
                />
              ) : currentSubScreen === 'stories' ? (
                <StoriesScreen
                  stories={stories}
                  onToggleBookmark={handleToggleBookmarkStory}
                  onOpenRelatedChallenge={challengeId => {
                    setCurrentSubScreen(null);
                    setCurrentTab('challenges');
                  }}
                />
              ) : currentSubScreen === 'profile' ? (
                <ProfileSettingsScreen
                  userProfile={userProfile}
                  onUpdateProfile={p => {
                    setUserProfile(p);
                    StorageService.saveProfile(p);
                  }}
                  onResetData={handleResetData}
                  onReplayOnboarding={handleReplayOnboarding}
                />
              ) : currentTab === 'home' ? (
                <HomeScreen
                  userProfile={userProfile}
                  challenges={challenges}
                  badges={badges}
                  campaigns={campaigns}
                  onNavigateTab={tab => {
                    setCurrentSubScreen(null);
                    setCurrentTab(tab);
                  }}
                  onOpenCampaigns={() => setCurrentSubScreen('campaigns')}
                  onOpenStories={() => setCurrentSubScreen('stories')}
                  onSelectCategoryFilter={cat => {
                    setSelectedCategoryFilter(cat);
                    setCurrentSubScreen(null);
                    setCurrentTab('challenges');
                  }}
                  onQuickCompleteAction={handleQuickCompleteAction}
                />
              ) : currentTab === 'assistant' ? (
                <AssistantScreen onAddCustomChallenge={handleAddCustomChallenge} />
              ) : currentTab === 'challenges' ? (
                <ChallengesScreen
                  challenges={challenges}
                  selectedCategoryFilter={selectedCategoryFilter}
                  onSelectCategoryFilter={setSelectedCategoryFilter}
                  onStartChallenge={handleStartChallenge}
                  onCompleteChallenge={handleCompleteChallenge}
                />
              ) : currentTab === 'impact' ? (
                <ImpactScreen
                  userProfile={userProfile}
                  impactRecords={impactRecords}
                  badges={badges}
                />
              ) : currentTab === 'poster' ? (
                <PosterGeneratorScreen
                  userProfile={userProfile}
                  impactRecords={impactRecords}
                  onAwardPosterPoints={handleAwardPosterPoints}
                />
              ) : null}
            </div>

            {/* Android Material 3 Bottom Navigation Bar */}
            <AndroidBottomNav
              currentTab={currentTab}
              onSelectTab={tab => {
                setCurrentSubScreen(null);
                setCurrentTab(tab);
              }}
            />
          </>
        )}
      </AndroidPhoneFrame>

      {/* Android Studio Code Hub Modal & ZIP Downloader */}
      <AndroidStudioCodeModal
        isOpen={isCodeModalOpen}
        onClose={() => setIsCodeModalOpen(false)}
      />
    </>
  );
}
